import {
  ArrayMaxSize, ArrayMinSize, IsArray, IsBoolean, IsIn, IsInt, IsNumber, IsOptional,
  IsString, IsUUID, Matches, Max, MaxLength, Min, ValidateNested,
} from 'class-validator';
import { Type } from 'class-transformer';

export class PosBillItemDto {
  @IsInt() @Min(1)
  productId!: number;

  @IsInt() @Min(1) @Max(999)
  quantity!: number;
}

export class PosDiscountDto {
  @IsIn(['flat', 'percent'])
  type!: 'flat' | 'percent';

  @IsNumber() @Min(0)
  value!: number;

  @IsOptional() @IsString() @MaxLength(80)
  reason?: string;
}

export class CreatePosBillDto {
  @IsInt() @Min(1)
  outletId!: number;

  /** generated by the till per bill; a retry with the same ref returns the same bill */
  @IsOptional() @IsUUID()
  clientRef?: string;

  @IsArray() @ArrayMinSize(1) @ArrayMaxSize(100)
  @ValidateNested({ each: true }) @Type(() => PosBillItemDto)
  items!: PosBillItemDto[];

  @IsIn(['cash', 'upi', 'card', 'other'])
  paymentMethod!: 'cash' | 'upi' | 'card' | 'other';

  @IsOptional() @IsIn(['takeaway', 'dine_in'])
  orderType?: 'takeaway' | 'dine_in';

  @IsOptional() @IsString() @MaxLength(80)
  customerName?: string;

  @IsOptional() @IsString() @MaxLength(20)
  customerMobile?: string;

  @IsOptional() @IsString() @MaxLength(300)
  note?: string;

  @IsOptional() @ValidateNested() @Type(() => PosDiscountDto)
  discount?: PosDiscountDto;
}

export class CancelPosBillDto {
  @IsString() @MaxLength(200)
  reason!: string;
}

export class OutletDto {
  @IsOptional() @IsString() @Matches(/^[A-Za-z0-9]{2,3}$/, { message: 'Code must be 2–3 letters or digits, e.g. BKW' })
  code?: string;

  @IsOptional() @IsString() @MaxLength(80)
  name?: string;

  @IsOptional() @IsString() @MaxLength(300)
  address?: string;

  @IsOptional() @IsString() @MaxLength(20)
  phone?: string;

  @IsOptional() @IsString() @MaxLength(15)
  gstin?: string;

  @IsOptional() @IsString() @MaxLength(20)
  fssai?: string;

  @IsOptional() @IsString() @MaxLength(300)
  billFooter?: string;

  @IsOptional() @IsInt() @Min(0) @Max(23)
  dayStartsAt?: number;

  @IsOptional() @IsIn(['both', 'bill', 'kot'])
  printMode?: 'both' | 'bill' | 'kot';

  @IsOptional() @IsInt() @Min(1) @Max(3)
  kotCopies?: number;

  @IsOptional() @IsBoolean()
  isActive?: boolean;

  @IsOptional() @IsInt()
  sortOrder?: number;

  /* online takeaway */
  @IsOptional() @IsBoolean()
  pickupEnabled?: boolean;

  /** YYYY-MM-DD; empty = open for takeaway now */
  @IsOptional() @IsString() @Matches(/^(\d{4}-\d{2}-\d{2})?$/, { message: 'Takeaway start date must be a date' })
  pickupOpensOn?: string;

  /** this kitchen cooks the delivery orders */
  @IsOptional() @IsBoolean()
  cooksDelivery?: boolean;

  @IsOptional() @IsNumber() @Min(-90) @Max(90)
  latitude?: number | null;

  @IsOptional() @IsNumber() @Min(-180) @Max(180)
  longitude?: number | null;

  @IsOptional() @IsString() @MaxLength(500)
  mapsUrl?: string;

  @IsOptional() @IsString() @MaxLength(200)
  pickupNote?: string;
}

export class OutletPriceDto {
  @IsInt() @Min(1)
  productId!: number;

  /** null / omitted = sell at the website price */
  @IsOptional() @IsNumber() @Min(0)
  price?: number | null;

  @IsBoolean()
  isAvailable!: boolean;
}

export class SaveOutletPricesDto {
  @IsArray() @ArrayMaxSize(2000)
  @ValidateNested({ each: true }) @Type(() => OutletPriceDto)
  prices!: OutletPriceDto[];
}

export class CopyOutletPricesDto {
  @IsInt() @Min(1)
  fromOutletId!: number;
}
